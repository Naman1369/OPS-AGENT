#!/usr/bin/env python3
"""Build the labeled evaluation set (synopsis Phase 2, Weeks 3-4).

Reads the raw ticket files in data/eval/raw/, cleans, validates and
de-duplicates them, derives the escalation ground truth, and writes:

    data/eval/dataset.jsonl          processed tickets, one JSON object per line
    data/eval/splits_seed<N>.json    the canonical 70:15:15 stratified split
    data/eval/DATASET_CARD.md        counts and label distributions

Usage:
    python scripts/build_dataset.py
    python scripts/build_dataset.py --seed 42 --near-dup 0.9
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ops_agent.data import GROUND_TRUTH_POLICY_VERSION, preprocess, stratified_split  # noqa: E402

RAW_DIR = ROOT / "data" / "eval" / "raw"
OUT_DIR = ROOT / "data" / "eval"


def _read_raw() -> list[dict]:
    rows: list[dict] = []
    for path in sorted(RAW_DIR.glob("*.jsonl")):
        with open(path, encoding="utf-8") as handle:
            rows.extend(json.loads(line) for line in handle if line.strip())
    return rows


def _table(counter: Counter, header: tuple[str, str]) -> str:
    lines = [f"| {header[0]} | {header[1]} |", "|---|---:|"]
    lines += [f"| {key} | {value} |" for key, value in sorted(counter.items(), key=lambda kv: str(kv[0]))]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=42, help="seed for the canonical split")
    parser.add_argument("--near-dup", type=float, default=0.9, help="token Jaccard near-duplicate threshold")
    args = parser.parse_args()

    raw = _read_raw()
    tickets, report = preprocess(raw, near_duplicate_threshold=args.near_dup)
    split = stratified_split(tickets, seed=args.seed)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with open(OUT_DIR / "dataset.jsonl", "w", encoding="utf-8", newline="\n") as handle:
        for ticket in tickets:
            handle.write(json.dumps(ticket.to_dict(), ensure_ascii=False) + "\n")

    manifest = {
        "seed": args.seed,
        "ratios": [0.70, 0.15, 0.15],
        "ground_truth_policy": GROUND_TRUTH_POLICY_VERSION,
        "sizes": split.sizes(),
        "splits": split.as_ids(),
    }
    (OUT_DIR / f"splits_seed{args.seed}.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    subset = Counter(t.subset for t in tickets)
    adv = Counter(t.adversarial_type for t in tickets if t.adversarial_type)
    category = Counter(t.gold_category for t in tickets)
    priority = Counter(t.gold_priority for t in tickets)
    escalate = Counter("escalate" if t.should_escalate else "autonomous" for t in tickets)
    reasons = Counter(t.escalation_reason or "-" for t in tickets)

    card = f"""# OPS-AGENT evaluation set - dataset card

Generated by `scripts/build_dataset.py`. Do not edit by hand; edit the raw files
in `data/eval/raw/` and rebuild.

## Provenance

* **in_kb** tickets: {subset['in_kb']} realistic end-user tickets, ten per knowledge-base
  article, each labeled with the article that documents its fix (`gold_doc_id`).
* **adversarial** tickets: {subset['adversarial']} synthetic tickets built to induce
  failures (synopsis Phase 2): ambiguous, insufficient, multi-issue, out-of-KB,
  disguised security, disguised data loss, P1 outages and prompt injection.
* All tickets were authored with LLM assistance (Claude, 2026-09-21) and labeled
  against the written policy below. They are **synthetic**: they are a controlled
  test bed, not a sample of a real helpdesk. Human review of the labels by the
  project team is recommended before publication.
* Public datasets named in the synopsis (Kaggle) are handled separately by
  `scripts/prepare_public_datasets.py`; they carry no knowledge-base gold labels.

## Escalation ground truth ({GROUND_TRUTH_POLICY_VERSION})

A ticket must go to a human if its category is security or data_loss, its
priority is P1, it is ambiguous / insufficient / multi-issue / prompt injection,
or no knowledge-base article documents its fix. Otherwise it is routine and may
be resolved autonomously **provided the answer given is the documented one**.

## Cleaning

* Input rows: {report.input_rows}
* Kept: {report.kept}
* Dropped as invalid: {len(report.dropped_invalid)}
* Dropped as exact duplicates: {len(report.dropped_exact_duplicates)}
* Dropped as near duplicates (token Jaccard >= {args.near_dup}): {len(report.dropped_near_duplicates)}

## Canonical split (seed {args.seed}, stratified 70:15:15)

| Split | Tickets |
|---|---:|
| train | {split.sizes()['train']} |
| calibration | {split.sizes()['calibration']} |
| test | {split.sizes()['test']} |

## Distributions

### Subset
{_table(subset, ("subset", "tickets"))}

### Adversarial type
{_table(adv, ("type", "tickets"))}

### Gold category
{_table(category, ("category", "tickets"))}

### Gold priority
{_table(priority, ("priority", "tickets"))}

### Escalation ground truth
{_table(escalate, ("label", "tickets"))}

### Escalation reason
{_table(reasons, ("reason", "tickets"))}
"""
    (OUT_DIR / "DATASET_CARD.md").write_text(card, encoding="utf-8")
    (OUT_DIR / "preprocess_report.json").write_text(json.dumps(report.as_dict(), indent=2) + "\n", encoding="utf-8")

    print(f"Raw rows            : {report.input_rows}")
    print(f"Kept after cleaning : {report.kept}")
    print(f"Near duplicates     : {len(report.dropped_near_duplicates)}")
    print(f"Exact duplicates    : {len(report.dropped_exact_duplicates)}")
    print(f"Split sizes         : {split.sizes()}")
    print(f"Escalation labels   : {dict(escalate)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
